  "1": "МБОУ Инженерный лицей №83 имени Пинского М.С. УГНТУ",
  "2": "Специализированного учебно-научного центра Федерального Государственного автономного образовательного учреждения высшего образования 'Уральский Федеральный Университет имени первого Президента России Б.Н.Ельцина'",
