const CONSISTENCY_PROMPT = `
Тебе предоставлены результаты нормализации названий школ. Применяя все правила выше, исправь оставшиеся нарушения. Особое внимание удели консистентности: если одна и та же школа встречается под разными названиями — приведи все варианты к одному, соответствующему правилам.
`;

const PASSES = [
  { mode: "rename", chunkSize: 250, order: "sort" },
  { mode: "consistency", chunkSize: 500, order: "sort" },
  { mode: "consistency", chunkSize: 500, order: "shuffle" },
] as const;

console.log("Reading unique school names...");
const schools = await getUniqueParticipationValues("school");
console.log(`\nFound ${schools.length} unique schools`);

const mapping = Object.fromEntries(schools.map((s) => [s, s]));

for (const { mode, chunkSize, order } of PASSES) {
  const values = [...new Set(Object.values(mapping))];
  const prompt =
    mode === "consistency"
      ? NORMALIZE_SCHOOLS_PROMPT + CONSISTENCY_PROMPT
      : NORMALIZE_SCHOOLS_PROMPT;

  console.log(`\nRunning ${mode} pass (${order}, ${values.length} values)...`);
  const replacements = await llmNormalize(prompt, values, { chunkSize, order });
  applyReplacements(mapping, replacements);
  console.log(
    `${new Set(Object.values(mapping)).size} unique values after ${mode}`,
  );
}

const changedOnly = Object.fromEntries(
  Object.entries(mapping).filter(([k, v]) => v !== k),
);
await writeMapping(changedOnly, "normalizedSchools.json");
